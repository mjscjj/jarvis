type PromptOptions struct {
	PrincipalOpenID string
	Location        *time.Location
	MaxChars        int
	// AllowSingleNewOverLimit preserves one complete atomic message after every
	// removable context message has been dropped. The limit is a coarse batching
	// boundary, not permission to truncate raw evidence or strand one message
	// forever behind an unchanged watermark.
	AllowSingleNewOverLimit bool
	// SystemPrompt is the human-editable M3 role and behavior prompt.
	SystemPrompt string
	// ToolCatalog is generated by the tool layer for agent-style engines. It is
	// empty for engines whose function tools are already described by schemas.
	ToolCatalog string
	// WorkRules 是已按 extract 阶段过滤并渲染好的可信工作规则 block。
	WorkRules string
	// SharedMemory is the same trusted global block M5 and chat receive.
	SharedMemory string
	// Skills 是已按 extract 阶段过滤的简短 Skill 目录。
	Skills string
}

var ErrPromptTooLarge = errors.New("extract prompt too large")

// outputContract closes the user prompt. It sits last on purpose: by the time
// the model finishes minutes of tool calls, an instruction from the middle of
// the system prompt is far behind it, and it drifts back into chat prose. The
// worked example matters as much as the rules — models copy shapes more
// reliably than they follow prose.
const outputContract = `

=========================  输出格式（最重要，最后再读一遍）  =========================

你的最后一条消息**必须是且只能是一个 JSON 对象**，从 { 开始，到 } 结束。

- 不要写任何开场白、说明、总结或结束语；
- 不要包 ` + "```json" + ` 代码围栏；
- 不要输出多个 JSON；
- 没有任何值得留下的线索时，输出 {"candidates": []}，不要用文字说明"本轮无线索"。

candidates 中每个元素都必须包含全部九个字段：action_type、status、title、target、
project_hint、source_message_ids、source_quote、payload、annotation。project_hint 判断不出来时写
空字符串 ""，不要省略这个字段。

annotation 是宽松 JSON 对象编码成的字符串（注意转义双引号），无补充时写 "{}"。
可用 brief 简述线索和不确定性，scene 用几句话解释当时现场，background 说明进一步理解所需背景；均可用自然语言，也可增加字段。不必填满，不为写说明扩大调查。
source_message_ids 是唯一的直接证据列表，要包含交办原文以及“这个/上述”指代的链接或事件所在消息。消息正文与背景由程序冻结，你只写说明和已有消息 ID。

完整示例（照着这个形状写）：

{
  "candidates": [
    {
      "action_type": "investigate",
      "status": "extracted",
      "title": "排查 agent-runtime 网关偶发 502",
      "target": "agent-runtime 网关 502",
      "project_hint": "agent-runtime",
      "source_message_ids": ["om_x1"],
      "source_quote": "今天线上又出现 502 了，麻烦帮忙看一下",
      "payload": "张伟在群里直接点名让我排查，目前只知道偶发、未定位到具体服务，也没有人认领。属于需要我介入的未闭环问题。已核验：近期没有相同 Todo。不确定：是否与昨天的发布相关。",
      "annotation": "{\"brief\":\"排查线上偶发 502，尚未定位服务。\",\"scene\":\"张伟在当前讨论中请求协助，还没有认领者。\"}"
    },
    {
      "action_type": "other",
      "status": "observing",
      "title": "Bax 评测数据集本周冻结",
      "target": "Bax 评测数据集冻结时间",
      "project_hint": "",
      "source_message_ids": ["om_x2"],
      "source_quote": "数据集这周五冻结，之后不再接收新样本",
      "payload": "李娜宣布的时间约束，由她本人负责推进，当前不需要我做什么，但会影响我后续提交样本的节奏，值得记住。",
      "annotation": "{\"brief\":\"本周五冻结数据集，目前无需行动。\"}"
    }
  ]
}

再说一次：**只输出这个 JSON 对象本身，前后不要有任何其它字符。**
`

func BuildPrompt(batch ChatBatch, unit ConversationUnit, counts []FactCount, now time.Time, opts PromptOptions) (Prompt, error) {
	if strings.TrimSpace(opts.PrincipalOpenID) == "" {
		return Prompt{}, fmt.Errorf("extract principal open_id is empty")
	}
	if opts.Location == nil {
		return Prompt{}, fmt.Errorf("extract prompt location is nil")
	}
	if opts.MaxChars <= 0 {
		return Prompt{}, fmt.Errorf("extract prompt max chars must be positive")
	}
	if len(unit.Messages) == 0 {
		return Prompt{}, fmt.Errorf("extract conversation unit %q has no messages", unit.Key)
	}

	trimmed := unit
	trimmed.Messages = append([]MessageContext(nil), unit.Messages...)
	system, err := prompttemplate.Render(prompttemplate.StageM3, opts.SystemPrompt, opts.WorkRules, "")
	if err != nil {
		return Prompt{}, fmt.Errorf("render M3 system prompt: %w", err)
	}
	system += "\n\nPRINCIPAL_OPEN_ID=" + opts.PrincipalOpenID
	if block := sharedmem.RenderBlock(opts.SharedMemory); block != "" {
		system += "\n\n" + block
	}
	if catalog := strings.TrimSpace(opts.ToolCatalog); catalog != "" {
		system += "\n\n" + catalog
	}
	if block := strings.TrimSpace(opts.Skills); block != "" {
		system += "\n\n" + block
	}
	for {
		user := renderUserPrompt(batch, trimmed, counts, now.In(opts.Location), opts.Location) + outputContract
		chars := utf8.RuneCountInString(system) + utf8.RuneCountInString(user)
		if chars <= opts.MaxChars {
			return Prompt{System: system, User: user}, nil
		}
		index := firstContextIndex(trimmed.Messages)
		if index < 0 {
			if opts.AllowSingleNewOverLimit && countUnitNewMessages(trimmed.Messages) == 1 {
				return Prompt{System: system, User: user}, nil
			}
			return Prompt{}, fmt.Errorf("%w: unit=%s chars=%d exceeds max_chars=%d after removing all context messages", ErrPromptTooLarge, unit.Key, chars, opts.MaxChars)
		}
		trimmed.Messages = append(trimmed.Messages[:index], trimmed.Messages[index+1:]...)
	}
}

func countUnitNewMessages(messages []MessageContext) int {
	count := 0
	for _, message := range messages {
		if message.IsNew {
			count++
		}
	}
	return count
}

func renderUserPrompt(batch ChatBatch, unit ConversationUnit, counts []FactCount, now time.Time, location *time.Location) string {
	sections := []string{
		"# 当前时间\n" + now.Format(time.RFC3339) + "（时区 " + location.String() + "）",
		"# 我的背景(principal)\n" + renderPrincipal(batch.Principal),
		"# 当前会话所属项目（详细）\n" + renderProject(batch.Project),
		"# 我的其他项目（精简，仅作归属参考）\n" + renderOtherProjects(batch.OtherProjects),
		"# 来源会话（Group）\n" + renderGroup(batch.Group),
		"# 参与者\n" + renderParticipants(unit.Participants),
		"# 相关资源\n" + renderResources(unit.Resources),
		"# 世界事实（明细未展开）\n" + renderFactCounts(counts),
		"# 最近有进展的任务（仅作背景）\n" + renderRecentTasks(batch.RecentTasks),
		"# 已存在的未闭环 Todo（仅作背景）\n" + renderOpenTodos(batch.OpenTodos),
		"# 会话记录\n" + renderConversation(unit.Messages, location),
	}
	return strings.Join(sections, "\n\n")
}

func renderPrincipal(principal *PrincipalContext) string {
	if principal == nil {
		return "(未设置——请在后台「我」中完善 principal 背景)"
	}
	parts := []string{fmt.Sprintf("open_id=%s name=%q", principal.OpenID, principal.Name)}
	if principal.Department != "" {
		parts = append(parts, fmt.Sprintf("department=%q", principal.Department))
	}
	if principal.Title != "" {
		parts = append(parts, fmt.Sprintf("title=%q", principal.Title))
	}
	if principal.LeaderOpenID != "" {
		parts = append(parts, fmt.Sprintf("leader_open_id=%s leader_name=%q", principal.LeaderOpenID, principal.LeaderName))
	}
	line := strings.Join(parts, " ")
	if summary := strings.TrimSpace(principal.Summary); summary != "" {
		line += "\n" + summary
	}
	return line
}

func renderOtherProjects(projects []OtherProjectContext) string {
	if len(projects) == 0 {
		return "(none)"
	}
	lines := make([]string, len(projects))
	for i, project := range projects {
		lines[i] = fmt.Sprintf("id=%d code=%q name=%q role=%s status=%s priority=%d", project.ID, project.Code, project.Name, project.Role, project.Status, project.Priority)
	}
	return strings.Join(lines, "\n")
}

func renderProject(project *ProjectContext) string {
	if project == nil {
		return "(none)"
	}
	line := fmt.Sprintf("id=%d code=%q name=%q role=%s status=%s priority=%d",
		project.ID, project.Code, project.Name, project.Role, project.Status, project.Priority)
	if summary := strings.TrimSpace(project.Summary); summary != "" {
		line += "\n" + summary
	}
	return line
}

func renderGroup(group GroupContext) string {
	line := fmt.Sprintf("chat_id=%s name=%q is_key_group=%t project_id=%s", group.ChatID, group.Name, group.IsKeyGroup, uint64PointerText(group.ProjectID))
	if strings.TrimSpace(group.Description) != "" {
		line += "\n群公告：" + group.Description
	}
	if summary := strings.TrimSpace(group.Summary); summary != "" {
		line += "\n" + summary
	}
	return line
}

func renderParticipants(participants []ParticipantContext) string {
	if len(participants) == 0 {
		return "(none)"
	}
	lines := make([]string, len(participants))
	for i, participant := range participants {
		line := fmt.Sprintf("open_id=%s name=%q role=%s is_leader=%t", participant.OpenID, participant.Name, participant.Role, participant.IsLeader)
		if participant.Title != "" {
			line += fmt.Sprintf(" title=%q", participant.Title)
		}
		if summary := strings.TrimSpace(participant.Summary); summary != "" {
			line += "\n" + summary
		}
		lines[i] = line
	}
	return strings.Join(lines, "\n")
}

func renderResources(resources []ResourceContext) string {
	if len(resources) == 0 {
		return "(none)"
	}
	lines := make([]string, len(resources))
	for i, resource := range resources {
		lines[i] = fmt.Sprintf("id=%d type=%s file_key=%q minute_token=%q doc_token=%q url=%q name=%q extracted_text=%q",
			resource.ID, resource.ResourceType, resource.FileKey, resource.MinuteToken, resource.DocToken, resource.URL, resource.Name, resource.ExtractedText)
	}
	return strings.Join(lines, "\n")
}

func renderFactCounts(counts []FactCount) string {
	if len(counts) == 0 {
		return "(none)"
	}
	lines := make([]string, 0, len(counts))
	for _, count := range counts {
		label := strings.TrimSpace(count.Label)
		if label == "" {
			label = fmt.Sprintf("%s:%d", count.SubjectType, count.SubjectID)
		}
		lines = append(lines, fmt.Sprintf("%s:%d「%s」今日 %d 条、近 7 天 %d 条 —— 需要细节先用 list-facts 查证据索引，再沿 source 指针读原始材料。",
			count.SubjectType, count.SubjectID, label, count.Today, count.Last7Days))
	}
	return strings.Join(lines, "\n")
}

func renderRecentTasks(tasks []RecentTaskContext) string {
	if len(tasks) == 0 {
		return "(none)"
	}
	lines := make([]string, len(tasks))
	for i, task := range tasks {
		summary := task.Summary
		if summary == "" {
			summary = "(no summary)"
		}
		progressAt := task.LastProgressAt
		if progressAt == "" {
			progressAt = "(unknown)"
		}
		lines[i] = fmt.Sprintf("task_id=%d title=%q status=%s summary=%q last_progress_at=%s",
			task.ID, task.Title, task.Status, summary, progressAt)
	}
	return strings.Join(lines, "\n")
}

func renderOpenTodos(todos []OpenTodoContext) string {
	if len(todos) == 0 {
		return "(none)"
	}
	lines := make([]string, len(todos))
	for i, todo := range todos {
		lines[i] = fmt.Sprintf("todo_id=%d action_type=%s title=%q status=%s", todo.ID, todo.ActionType, todo.Title, todo.Status)
	}
	return strings.Join(lines, "\n")
}

func renderConversation(messages []MessageContext, location *time.Location) string {
	lines := make([]string, len(messages))
	for i, message := range messages {
		kind := "context"
		if message.IsNew {
			kind = "new"
		}
		content := strings.ReplaceAll(strings.TrimSpace(message.Content), "\r\n", "\n")
		content = strings.ReplaceAll(content, "\n", "\n    ")
		lines[i] = fmt.Sprintf("[%s] msg_id=%s source=%s message_type=%s time=%s sender_open_id=%s is_leader=%t sender_name=%q: %s",
			kind, message.MessageID, message.Source, message.MessageType,
			time.UnixMilli(message.CreateTime).In(location).Format(time.RFC3339),
			message.SenderOpenID, message.IsLeader, message.SenderName, content)
	}
	return strings.Join(lines, "\n")
}

func firstContextIndex(messages []MessageContext) int {
	for i, message := range messages {
		if !message.IsNew {
			return i
		}
	}
	return -1
}

func uint64PointerText(value *uint64) string {
	if value == nil {
		return "null"
	}
	return fmt.Sprintf("%d", *value)
}
